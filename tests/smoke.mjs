// Headless smoke test: node tests/smoke.mjs  (needs local server on :8765)
import { createRequire } from "module";
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PW_PATH || "playwright");
const BASE = process.env.BASE || "http://localhost:8765/";
const errors = []; const results = [];
const ok = (name, cond, extra) => { results.push([name, !!cond, extra || ""]); console.log((cond ? "PASS " : "FAIL ") + name + (extra ? " — " + extra : "")); };
const browser = await chromium.launch(process.env.CHROME ? { executablePath: process.env.CHROME } : {});
const page = await browser.newPage({ viewport: { width: 1300, height: 950 } });
page.on("console", (m) => { if (m.type() === "error") errors.push(m.text()); });
page.on("pageerror", (e) => errors.push(String(e)));
await page.goto(BASE);
await page.evaluate(() => localStorage.clear());
await page.reload();
await page.fill("#welcomeName", "Alexa");
await page.locator(".age-btn", { hasText: /^10$/ }).click();
await page.click("#btnStartAdventure");
ok("onboarding → home", await page.isVisible("#view-home"));
await page.click("#btnContinue");
if (await page.isVisible("#view-track")) await page.locator(".lesson-btn").first().click();
ok("Roblox mission 1 opens", await page.isVisible("#view-play") && (await page.textContent("#playTitle")).includes("Bridge"));
const W2S = async (x, y) => { const b = await page.locator(".st-stage canvas").boundingBox(); return [b.x + (x / 32) * b.width, b.y + ((14 - y) / 16) * b.height]; };
await page.click('[data-act="part"]');
await page.waitForFunction(() => /drag/i.test(document.querySelector("#bubble").textContent), null, { timeout: 5000 });
ok("tutor reacts to Insert Part", true);
const [sx, sy] = await W2S(13, 11); const [tx, ty] = await W2S(11, 3);
await page.mouse.move(sx, sy); await page.mouse.down();
for (let i = 1; i <= 12; i++) await page.mouse.move(sx + (tx - sx) * i / 12, sy + (ty - sy) * i / 12);
await page.mouse.up();
await page.waitForFunction(() => /Play/.test(document.querySelector("#bubble").textContent), null, { timeout: 5000 });
ok("drag part into place advances step", true);
const x0 = await page.evaluate(() => ccDebug.engine().av.x);
await page.click('[data-act="play"]');
await page.waitForTimeout(900);
const x1 = await page.evaluate(() => ccDebug.engine().av.x);
ok("avatar moves on Play", x1 > x0 + 1, x0.toFixed(1) + " → " + x1.toFixed(1));
await page.screenshot({ path: "/workspace/cc-roblox-mission.png" });
await page.waitForSelector(".tb-win", { timeout: 15000 });
ok("mission 1 completes (win + celebration)", true, await page.textContent(".tb-xp"));
await page.waitForTimeout(400);
await page.screenshot({ path: "/workspace/cc-roblox-win.png" });
// Luau color
await page.evaluate(() => startMission("rb5"));
await page.locator(".st-block", { hasText: "Make it red" }).click();
await page.waitForTimeout(400);
await page.click('[data-act="play"]');
await page.waitForTimeout(500);
const col = await page.evaluate(() => ccDebug.engine().find("Platform").color);
ok("Luau snippet changes part color", col === "#ff0000", col);
await page.waitForTimeout(3000);
// error explanation
await page.evaluate(() => { const e = ccDebug.engine(); e.stop("t"); e.ta.value = "local platform = workspace.Platfrom\nplatform.Color = Color3.new(0,0,1)"; });
await page.click('[data-act="play"]'); await page.waitForTimeout(400);
const out = await page.textContent(".st-output");
ok("friendly script error", /no part named "Platfrom"/.test(out), out.slice(-90));
const ers = errors.filter((e) => !/favicon/.test(e));
ok("no console errors", ers.length === 0, ers.join(" | "));
if (process.env.EXTRA) { const mod = await import(process.env.EXTRA); await mod.default(page, ok); }
await browser.close();
const fails = results.filter((r) => !r[1]).length;
console.log(fails ? fails + " FAILED" : "ALL PASSED"); process.exit(fails ? 1 : 0);
